"""Documentation kept in step with the live environment.

For each customer, Fenrir writes knowledge-base articles (category "Documentation (auto)") from current data:
an environment overview, the network (subnets, gateways, notable unmanaged equipment), Microsoft 365 (domains,
licences, MFA, standards) and the device inventory. They refresh daily, or on demand. A new revision is stored only
when the content changes, so the revision history doubles as a change log of the environment.

Anything written below the line ``--- Notes (kept when this page refreshes) ---`` is preserved across refreshes,
so engineers can annotate generated pages without losing their notes.
"""

from __future__ import annotations

from collections import Counter
from datetime import timedelta

from sqlalchemy import select
from sqlalchemy.orm import Session

from . import audit, documentation
from .models import (BackupPlan, Contact, Device, KbArticle, M365Connection, M365StandardRun, NetworkNode, NetworkSubnet, Tenant,
                     utcnow)

CATEGORY = "Documentation (auto)"
NOTES_MARKER = "--- Notes (kept when this page refreshes) ---"
PAGES = ("overview", "network", "microsoft-365", "devices")


def _table(headers: list[str], rows: list[list]) -> str:
    if not rows:
        return "_None recorded._"
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c).replace("|", "/") if c not in (None, "") else "-" for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _devices(db: Session, tenant: Tenant) -> list[Device]:
    return db.execute(select(Device).where(Device.tenant_id == tenant.id, Device.approved.is_(True)).order_by(Device.hostname)).scalars().all()


def overview(db: Session, tenant: Tenant) -> str:
    devices = _devices(db, tenant)
    platforms = Counter(d.platform for d in devices)
    servers = [d for d in devices if "server" in (d.os_version or "").lower()]
    contacts = db.execute(select(Contact).where(Contact.account_tenant_id == tenant.id).order_by(Contact.is_primary.desc(), Contact.name)
                          .limit(15)).scalars().all()
    subnets = db.execute(select(NetworkSubnet).where(NetworkSubnet.tenant_id == tenant.id)).scalars().all()
    unmanaged = db.execute(select(NetworkNode).where(NetworkNode.tenant_id == tenant.id, NetworkNode.device_id.is_(None),
                                                     NetworkNode.ignored.is_(False))).scalars().all()
    plans = db.execute(select(BackupPlan).where(BackupPlan.tenant_id == tenant.id)).scalars().all()
    return "\n\n".join([
        f"# {tenant.name}: environment overview",
        "Generated by Fenrir from live data. Edit only below the notes line at the end.",
        "## Contacts\n" + _table(["Name", "Email", "Phone", "Role"], [[c.name + (" (primary)" if c.is_primary else ""), c.email, c.phone, c.title]
                                                                    for c in contacts]),
        "## Managed devices\n" + _table(["Platform", "Devices"], [[p, n] for p, n in sorted(platforms.items())]),
        "## Servers\n" + _table(["Server", "Operating system", "Criticality"], [[d.hostname, d.os_version, d.criticality] for d in servers]),
        "## Network\n" + _table(["Subnet", "Gateway"], [[s.cidr, s.gateway_ip] for s in subnets]) +
        f"\n\n{len(unmanaged)} unmanaged device(s) seen on the network (see the Network page).",
        "## Backup\n" + _table(["Plan", "Provider", "Status"], [[p.name, getattr(p, "provider", ""), getattr(p, "status", "")] for p in plans]),
    ])


def network(db: Session, tenant: Tenant) -> str:
    subnets = db.execute(select(NetworkSubnet).where(NetworkSubnet.tenant_id == tenant.id).order_by(NetworkSubnet.cidr)).scalars().all()
    nodes = db.execute(select(NetworkNode).where(NetworkNode.tenant_id == tenant.id, NetworkNode.ignored.is_(False))
                       .order_by(NetworkNode.subnet, NetworkNode.ip)).scalars().all()
    notable = [n for n in nodes if n.kind in ("gateway", "network", "printer", "server", "camera", "virtual") or n.device_id is None]
    return "\n\n".join([
        f"# {tenant.name}: network",
        "Discovered by Fenrir agents (Network → Topology). Edit only below the notes line at the end.",
        "## Subnets\n" + _table(["Subnet", "Gateway"], [[s.cidr, s.gateway_ip] for s in subnets]),
        "## Equipment\n" + _table(["IP", "Name", "Kind", "MAC", "Vendor", "Open ports", "Managed"],
                                  [[n.ip, n.hostname, n.kind, n.mac, n.vendor, ", ".join(str(p) for p in n.open_ports or []),
                                    "yes" if n.device_id else "no"] for n in notable[:500]]),
    ])


def microsoft_365(db: Session, tenant: Tenant) -> str:
    sections = [f"# {tenant.name}: Microsoft 365", "From the last directory sync. Edit only below the notes line at the end."]
    connections = db.execute(select(M365Connection).where(M365Connection.tenant_id == tenant.id)).scalars().all()
    if not connections:
        sections.append("_No Microsoft 365 tenant is connected._")
    for connection in connections:
        snap = connection.snapshot or {}
        insights = snap.get("insights") or {}
        mfa = insights.get("mfa") or {}
        domains = [d.get("id") for d in snap.get("domains") or [] if d.get("isVerified")]
        sections.append(f"## {connection.tenant_name or connection.name} ({connection.directory_id})\n"
                        f"Connection: {connection.auth_mode or 'app'}. Users: {insights.get('users', '-')}, enabled {insights.get('enabledUsers', '-')}. "
                        f"MFA registered: {mfa.get('percent', '-')}%. Verified domains: {', '.join(domains) or '-'}.")
        sections.append(_table(["Licence", "Assigned", "Purchased"],
                               [[s.get("skuPartNumber"), s.get("consumedUnits"), (s.get("prepaidUnits") or {}).get("enabled")]
                                for s in snap.get("licenses") or []]))
        runs = db.execute(select(M365StandardRun).where(M365StandardRun.connection_id == connection.id, M365StandardRun.action == "evaluate")
                          .order_by(M365StandardRun.at.desc()).limit(50)).scalars().all()
        latest = {}
        for run in runs:
            latest.setdefault(run.standard, run)
        if latest:
            sections.append(_table(["Standard", "State", "Detail"],
                                   [[k, r.status, (r.details or {}).get("detail", "")] for k, r in sorted(latest.items())]))
    return "\n\n".join(sections)


def devices_page(db: Session, tenant: Tenant) -> str:
    devices = _devices(db, tenant)
    return "\n\n".join([
        f"# {tenant.name}: devices",
        "Managed devices from Fenrir agents. Edit only below the notes line at the end.",
        _table(["Device", "Platform", "Operating system", "Serial", "IP addresses", "Criticality"],
               [[d.hostname, d.platform, d.os_version, d.serial_number, ", ".join((d.inventory or {}).get("ipAddresses") or []),
                 d.criticality] for d in devices]),
    ])


BUILDERS = {"overview": ("Environment overview", overview), "network": ("Network", network),
            "microsoft-365": ("Microsoft 365", microsoft_365), "devices": ("Devices", devices_page)}


def refresh(db: Session, tenant: Tenant, actor: str = "system:autodoc") -> list[dict]:
    results = []
    for key, (title, build) in BUILDERS.items():
        generated = build(db, tenant)
        tag = f"auto-doc:{key}"
        article = next((a for a in db.execute(select(KbArticle).where(KbArticle.tenant_id == tenant.id, KbArticle.category == CATEGORY))
                        .scalars() if tag in (a.tags or [])), None)
        notes = ""
        if article is not None and NOTES_MARKER in (article.body or ""):
            notes = article.body.split(NOTES_MARKER, 1)[1].strip()
        body = f"{generated}\n\n{NOTES_MARKER}\n{notes}".rstrip() + "\n"
        if article is None:
            article = KbArticle(tenant_id=tenant.id, title=f"{tenant.name}: {title}", category=CATEGORY, tags=["auto-doc", tag],
                                body=body, author=actor)
            db.add(article)
            changed = True
        else:
            changed = article.body != body
            if changed:
                article.body, article.updated_at, article.author = body, utcnow(), actor
        if changed:
            documentation.snapshot(db, article, actor)
        results.append({"page": key, "articleId": article.id, "changed": changed})
    audit.record(db, actor, "documentation.refreshed", tenant.name, tenant.id, changed=sum(1 for r in results if r["changed"]))
    return results


def tick(db: Session) -> None:
    """Daily refresh for customers that opted in (Tenant.settings["autoDocumentation"] = true)."""
    for tenant in db.execute(select(Tenant).where(Tenant.kind == "customer")).scalars():
        config = (tenant.settings or {}).get("autoDocumentation") or {}
        if not config.get("enabled"):
            continue
        last = config.get("lastRefreshAt")
        if last and utcnow() - _parse(last) < timedelta(hours=23):
            continue
        refresh(db, tenant)
        tenant.settings = {**(tenant.settings or {}), "autoDocumentation": {**config, "lastRefreshAt": utcnow().isoformat()}}
        db.commit()


def _parse(value: str):
    from datetime import datetime

    return datetime.fromisoformat(value.rstrip("Z"))
